// Writes the two copies of the table the username skeleton maps through, from Unicode's own files:
//
//   node scripts/confusables.mjs <confusables.txt> <license.txt>
//
// confusables.txt is https://www.unicode.org/Public/<version>/security/confusables.txt and license.txt is
// https://www.unicode.org/license.txt. One run writes Ward's copy (api/src/db/confusables.ts) and the library's
// (shared-library/src/core/confusables.ts): the library ships as a bundle apps copy, so it can't import Ward's api/,
// and both copies hold the same mappings from the same file. Each module keeps the mappings only (the source's
// comments are most of its size), and its header records the version, the date and the SHA-256 of the file it came
// from, with Unicode's licence notice, which has to travel with the data. A new version changes some skeletons: ship
// it with a dated migration that recomputes users.username_skeleton in Ward and a library migration that recomputes
// auth_users.username_skeleton.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [sourcePath, licensePath] = process.argv.slice(2);
if (sourcePath === undefined || licensePath === undefined) {
  console.error("usage: node scripts/confusables.mjs <confusables.txt> <license.txt>");
  process.exit(1);
}

/** Each copy, and the line of its header that names the function mapping through it. */
const COPIES = [
  { path: "../api/src/db/confusables.ts", user: "which `usernameSkeleton`\n * in `./users.ts` uses." },
  {
    path: "../shared-library/src/core/confusables.ts",
    user: "which `usernameSkeleton`\n * in `./username-skeleton.ts` uses.",
  },
];

const source = readFileSync(sourcePath);
const text = source.toString("utf8");
const license = readFileSync(licensePath, "utf8").trim();

const header = (name) => {
  const match = new RegExp(`^# ${name}: (.+)$`, "m").exec(text);
  if (match === null) throw new Error(`${sourcePath} has no "# ${name}:" line`);
  return match[1].trim();
};
const version = header("Version");
const date = header("Date");
const sha256 = createHash("sha256").update(source).digest("hex");

// A data line is `<code point> ;\t<prototype code points> ;\tMA\t# comment`.
const mappings = [];
for (const line of text.split("\n")) {
  const match = /^([0-9A-F]{4,6}) ;\t([0-9A-F]{4,6}(?: [0-9A-F]{4,6})*) ;\tMA\t/.exec(line);
  if (match !== null) mappings.push(`${match[1]};${match[2]}`);
  else if (/^[0-9A-F]/.test(line)) throw new Error(`unexpected data line: ${line}`);
}
if (mappings.length === 0) throw new Error(`${sourcePath} holds no mappings`);

const notice = license
  .split("\n")
  .map((line) => (line === "" ? " *" : ` * ${line}`))
  .join("\n");

const module = (user) => `/**
 * Unicode's confusables table (UTS #39, Unicode Security Mechanisms), version
 * ${version}: the code point each look-alike maps to, ${user} ${mappings.length} mappings.
 *
 * Generated by \`scripts/confusables.mjs\`; don't edit it by hand. Source:
 * https://www.unicode.org/Public/${version}/security/confusables.txt
 * Date: ${date}
 * SHA-256: ${sha256}
 *
 * Each line is a code point, \`;\`, then the code points of its prototype, all
 * in hex: \`0430;0061\` maps Cyrillic а to Latin a. Only the mappings are kept;
 * the source's comments (the names and glyphs) are most of its size.
 *
 * The data is Unicode's, under this notice:
 *
${notice}
 */
export const CONFUSABLES = \`${mappings.join("\n")}\`;
`;

for (const copy of COPIES) {
  writeFileSync(new URL(copy.path, import.meta.url), module(copy.user));
  console.log(`${copy.path.slice(3)}: Unicode ${version}, ${mappings.length} mappings, sha256 ${sha256}`);
}
